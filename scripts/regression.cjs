const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const originalResolve = Module._resolveFilename;
Module._resolveFilename = function(request, parent, ...rest) { return originalResolve.call(this, request.startsWith('@/') ? path.join(root, request.slice(2)) : request, parent, ...rest); };
require.extensions['.ts'] = function(module, filename) {
  const compiled = ts.transpileModule(fs.readFileSync(filename,'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  module._compile(compiled,filename);
};
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'life-six-regression-'));
process.env.LIFE_DATA_DIR = directory;
const { todayKey, addDateDays, dateBounds } = require('../lib/date.ts');
const { dailyCapacity, habitSummary } = require('../lib/planning.ts');
const { buildStats } = require('../lib/recommend.ts');
const { sortDailyTasks } = require('../lib/task-workflow.ts');
const { validateBackup } = require('../lib/validation.ts');
const store = require('../lib/store.ts');
const today = todayKey();
const now = new Date().toISOString();
const task = (id, extra = {}) => ({ id, title: id, description: '', date: today, dimension_primary: '心智', dimension_secondary: null, type: '临时任务', priority: 'B', status: '未开始', goal_id: null, project_id: null, habit_id: null, is_habit: false, is_must_today: false, due_date: null, due_time: null, reminder_time: null, calendar_sync_status: 'none', estimated_minutes: 30, result_note: '', checklist: [], created_at: now, completed_at: null, postponed_count: 0, is_focus: false, focus_order: null, ...extra });
const request = (body, method = 'POST') => new Request('http://localhost/test', { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
const context = (id) => ({ params: Promise.resolve({ id }) });
async function run() {
  let state = await store.readState();
  validateBackup(state);
  state.tasks = [task('deadline', { due_date: today }), task('future', { date: addDateDays(dateBounds('week').end, 1), status: '完成' })];
  await store.writeState(state);
  const route = require('../app/api/tasks/[id]/route.ts');
  const postponed = await route.PATCH(request({ status: '延期', date: addDateDays(today, 2), due_date: addDateDays(today, 2) }, 'PATCH'), context('deadline'));
  assert.equal(postponed.status, 200);
  state = await store.readState();
  assert.equal(state.tasks[0].due_date, today, 'postponing must preserve real deadline');
  assert.equal(state.tasks[0].date, addDateDays(today, 2));
  assert.equal(buildStats(state).week_completed, 0, 'next week excluded');
  state.tasks = [task('long', { estimated_minutes: 150 }), task('short', { estimated_minutes: 15 })];
  state.daily_plans = { [today]: { available_minutes: 120, buffer_minutes: 30, focus_limit: 1 } };
  assert.equal(dailyCapacity(state).overloaded, true);
  assert.deepEqual(sortDailyTasks(state.tasks, state).map((t) => t.id), ['long', 'short']);
  state.tasks = [task('wealth', { dimension_primary: '财富' }), task('relationship', { dimension_primary: '关系' })];
  state.dimension_priority_order = ['关系', '心智', '财富', '身体', '感受', '精神'];
  assert.equal(sortDailyTasks(state.tasks, state)[0].id, 'relationship', 'preferences affect ranking');
  state.habits = [{ id: 'habit', title: '练琴', frequency: '每周自由3次', weekdays: [], dimension_primary: '感受', estimated_minutes: 15, priority: 'B', active: true, created_at: now }];
  state.tasks = [task('old-habit', { date: addDateDays(today, -1), is_habit: true, habit_id: 'habit', source: 'habit' })];
  await store.writeState(state);
  await store.ensureTodayHabitTasks();
  state = await store.readState();
  assert.equal(state.tasks.find((t) => t.id === 'old-habit').status, '未记录');
  const mtime = fs.statSync(path.join(directory,'app-state.json')).mtimeMs;
  await store.ensureTodayHabitTasks();
  assert.equal(fs.statSync(path.join(directory,'app-state.json')).mtimeMs, mtime, 'GET initialization is idempotent');
  const hash = fs.readFileSync(path.join(directory,'app-state.json'),'utf8');
  const restore = require('../app/api/restore/route.ts');
  const bad = await restore.POST(request({ ...state, tasks: [task('bad', { estimated_minutes: 'wrong' })] }));
  assert.equal(bad.status, 400);
  assert.equal(fs.readFileSync(path.join(directory,'app-state.json'),'utf8'),hash);
  const revisionBeforeRestore = state.revision || 0;
  await restore.POST(request({ ...state, revision: Math.max(0, revisionBeforeRestore - 10) }));
  state = await store.readState();
  assert.equal(state.revision, revisionBeforeRestore + 1, 'restored data must get a newer revision so open clients accept it');
  assert.ok(fs.readdirSync(path.join(directory,'backups')).some((name) => name.includes('before-restore')));
  await Promise.all(Array.from({ length: 12 }, (_, i) => store.updateState((s) => { s.tasks.push(task('concurrent-'+i)); })));
  assert.equal((await store.readState()).tasks.filter((t) => t.id.startsWith('concurrent-')).length, 12);
  const nextWeek = require('../app/api/goals/next-week/route.ts');
  await store.updateState((s) => { s.goals = [{ id: 'goal', title: '客户验证', dimension_primary: '财富', success_metric: '收到需求确认', time_horizon: '90天', deadline: null, status: '进行中', why: '', created_at: now, cycle_focus: '本周期重点', ai_breakdown: JSON.stringify({ current_week_tasks: [{ id: 'action', title: '确认客户需求' }] }) }]; });
  let before = await store.readState();
  await nextWeek.POST(); await nextWeek.POST();
  state = await store.readState();
  assert.equal(state.tasks.length, before.tasks.length, 'generation must not schedule tasks');
  assert.equal(state.week_candidates.length, 1, 'generation is idempotent');
  const candidate = state.week_candidates[0];
  assert.equal((await nextWeek.PUT(request({ selections: [{ id: candidate.id, date: candidate.week, estimated_minutes: 1000 }] }, 'PUT'))).status, 400);
  assert.equal((await nextWeek.PUT(request({ selections: [{ id: candidate.id, date: candidate.week, estimated_minutes: 30 }] }, 'PUT'))).status, 200);
  await nextWeek.PUT(request({ selections: [{ id: candidate.id, date: candidate.week, estimated_minutes: 30 }] }, 'PUT'));
  state = await store.readState();
  assert.equal(state.tasks.filter((t) => t.week_task_id === candidate.id).length, 1);
  const quick = require('../app/api/reviews/quick/route.ts');
  const review = { date: today, wins: '完成访谈', blockers: '减少任务', tomorrow_first_text: '整理访谈证据' };
  assert.equal((await quick.POST(request(review))).status, 200);
  await quick.POST(request(review));
  state = await store.readState();
  assert.equal(state.daily_reviews.length, 1);
  assert.equal(state.tasks.filter((t) => t.title === review.tomorrow_first_text).length, 1);
  assert.equal(state.tasks.find((t) => t.title === review.tomorrow_first_text).due_date, null);
  console.log('PASS: deadlines, week boundaries, time capacity, preference ranking, habit history, idempotent reads, restore validation/snapshots, concurrent updates, candidate scheduling, quick review.');
  console.log('Isolated test data:', directory);
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
