const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename);
const {habitCalendarStats}=require('../lib/habit-calendar.ts');
const habit={id:'daily',frequency:'每日'};
const done=(date,extra={})=>({habit_id:'daily',date,status:'完成',...extra});
const tasks=[done('2026-10-30'),done('2026-10-31'),done('2026-11-01'),done('2026-11-01'),done('2026-11-03'),done('2026-11-04'),done('2026-11-05',{status:'未开始'}),done('2026-11-06'),done('invalid'),done('2026-11-04',{habit_id:'other'})];
let stats=habitCalendarStats(habit,tasks,'2026-11-05');
assert.equal(stats.totalDays,5,'duplicate, future and unrelated records do not inflate cumulative days');
assert.equal(stats.monthDays,3);
assert.equal(stats.currentStreak,2,'unfinished today retains the streak through yesterday');
assert.equal(stats.longestStreak,3,'a streak can cross month boundaries');
assert.equal(stats.weekDays,2,'week totals use habit dates rather than completion timestamps');
tasks.push(done('2026-11-05'));
stats=habitCalendarStats(habit,tasks,'2026-11-05');
assert.equal(stats.currentStreak,3,'checking off today extends the streak');
assert.equal(habitCalendarStats(habit,tasks,'2026-11-08').currentStreak,0,'a missed full day breaks the current streak');
assert.equal(habitCalendarStats(habit,tasks,'2026-11-05','2026-10').monthDays,2,'browsing history counts the selected month');
assert.equal(habitCalendarStats({...habit,frequency:'每周3次'},tasks,'2026-11-05').currentStreak,null,'weekly habits are not judged by consecutive daily attendance');
assert.equal(habitCalendarStats(habit,[],'2026-11-05').totalDays,0);
console.log('PASS: habit calendar unique days, monthly and weekly totals, daily streaks and non-daily habits.');
